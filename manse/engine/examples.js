/* 빠른 검색을 위해 길이 순으로 — 긴 조각이 먼저 걸려야 정확하다 */
const SORTED = EXAMPLES.slice().sort((a, b) => b.k.length - a.k.length);

/**
 * 글에 들어 있는 조언을 찾아 예시를 돌려준다.
 * @param {string|string[]} text 본문
 * @param {number} max 최대 몇 개까지
 */
export function examplesFor(text, max = 2) {
  const t = [].concat(text).filter(x => typeof x === "string").join("\n");
  if (!t) return [];
  const out = [];
  for (const e of SORTED) {
    if (out.length >= max) break;
    if (t.indexOf(e.k) < 0) continue;
    for (const x of e.ex) {
      if (out.length >= max) break;
      if (out.indexOf(x) < 0) out.push(x);
    }
  }
  return out;
}

/** 예시가 붙는 조언인지 */
export function hasExample(text) {
  const t = String(text || "");
  return SORTED.some(e => t.indexOf(e.k) >= 0);
}

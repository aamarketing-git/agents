/* ───────── 산출 ───────── */

function pillarsOf(saju) {
  return POS.map(k => {
    const p = saju.pillars[k];
    if (!p) return null;
    return { key:k, ko:POS_KO[k], stem:p.stem, branch:p.branch, gapja:p.gapja,
             stemCn:p.stemCn, branchCn:p.branchCn };
  }).filter(Boolean);
}

/**
 * 신살 전체
 * @returns {{byPillar:Object, twelve:Object, list:Array, good:number, bad:number, note:string}}
 */
export function buildSinsal(saju) {
  const ps = pillarsOf(saju);
  const ds = saju.pillars.day.stem;
  const mb = saju.pillars.month.branch;
  const db = saju.pillars.day.branch;
  const yb = saju.pillars.year.branch;
  const gongmang = saju.gongmang || [];

  const hits = [];   // { name, where:[pos...] }
  const add = (name, keys) => {
    if (!keys || !keys.length) return;
    const f = hits.find(h => h.name === name);
    const tgt = f || { name, where: [] };
    keys.forEach(k => { if (k && tgt.where.indexOf(k) < 0) tgt.where.push(k); });
    tgt.where.sort((a, b) => POS.indexOf(a) - POS.indexOf(b));
    if (!f && tgt.where.length) hits.push(tgt);
  };
  const byBranch = (name, arr) => add(name, ps.filter(p => arr && arr.indexOf(p.branch) >= 0).map(p => p.key));
  const byStem   = (name, arr) => add(name, ps.filter(p => arr && arr.indexOf(p.stem) >= 0).map(p => p.key));

  /* ── 길신 ── */
  byBranch("천을귀인", S_CHEONEUL[ds]);
  const cd = CHEONDEOK[mb];
  if (cd) add("천덕귀인", ps.filter(p => p.stem === cd || p.branch === cd).map(p => p.key));
  const wd = WOLDEOK[S_SAMHAP[mb]];
  if (wd) byStem("월덕귀인", [wd]);
  byBranch("문창귀인", [MUNCHANG[ds]]);
  byBranch("학당귀인", [HAKDANG[ds]]);
  byBranch("태극귀인", TAEGEUK[ds]);
  byBranch("금여",     [GEUMYEO[ds]]);
  byBranch("건록",     [GEONROK[ds]]);
  byBranch("암록",     [AMROK[ds]]);

  /* ── 흉살 ── */
  const dohwa = [];
  [db, yb].forEach(b => { const g = S_SAMHAP[b]; if (g) dohwa.push(JI[(JI.indexOf(SAENGJI[g]) + 1) % 12]); });
  byBranch("도화", dohwa);
  byBranch("홍염살", [HONGYEOM[ds]]);
  const yeokma = [];
  [db, yb].forEach(b => { const g = S_SAMHAP[b]; if (g) yeokma.push(JI[(JI.indexOf(SAENGJI[g]) + 6) % 12]); });
  byBranch("역마", yeokma);
  const hwagae = [];
  [db, yb].forEach(b => { const g = S_SAMHAP[b]; if (g) hwagae.push(JI[(JI.indexOf(SAENGJI[g]) + 8) % 12]); });
  byBranch("화개", hwagae);
  if (S_YANGIN[ds]) byBranch("양인", [S_YANGIN[ds]]);

  add("백호살",  ps.filter(p => BAEKHO.indexOf(p.gapja) >= 0).map(p => p.key));
  /* 괴강은 일주로 보는 것이 본래 법이다. 네 기둥 전부로 잡으면 절반 가까이 걸려 뜻이 흐려진다 */
  if (GOEGANG.indexOf(saju.pillars.day.gapja) >= 0) add("괴강살", ["day"]);
  if (GORAN.indexOf(saju.pillars.day.gapja) >= 0) add("고란살", ["day"]);

  const chimPos = ps.filter(p => HYEONCHIM_G.indexOf(p.stem) >= 0 || HYEONCHIM_J.indexOf(p.branch) >= 0).map(p => p.key);
  if (chimPos.length >= 2) add("현침살", chimPos);

  /* 원진·귀문 — 사주 안의 두 지지가 짝을 이룰 때 */
  const pairHit = (table, name) => {
    const out = [];
    for (let i = 0; i < ps.length; i++)
      for (let j = i + 1; j < ps.length; j++)
        if (table[ps[i].branch] === ps[j].branch) { out.push(ps[i].key); out.push(ps[j].key); }
    add(name, out);
  };
  pairHit(WONJIN, "원진살");
  pairHit(GWIMUN, "귀문관살");

  /* 천라지망 — 술해 또는 진사가 함께 있을 때 */
  const bs = ps.map(p => p.branch);
  if (bs.indexOf("술") >= 0 && bs.indexOf("해") >= 0)
    add("천라지망", ps.filter(p => p.branch === "술" || p.branch === "해").map(p => p.key));
  if (bs.indexOf("진") >= 0 && bs.indexOf("사") >= 0)
    add("천라지망", ps.filter(p => p.branch === "진" || p.branch === "사").map(p => p.key));

  byBranch("급각살", GEUPGAK[mb]);
  if (TANGHWA[db]) byBranch("탕화살", TANGHWA[db]);

  /* ── 십이신살 — 년지 삼합 기준, 기둥마다 하나씩 ── */
  const grp = S_SAMHAP[yb];
  const start = grp ? (JI.indexOf(SAENGJI[grp]) + 9) % 12 : 0;   // 겁살 = 생지 - 3
  const twelveOf = (b) => TWELVE[((JI.indexOf(b) - start) % 12 + 12) % 12];
  const twelve = {};
  ps.forEach(p => {
    const nm = twelveOf(p.branch);
    twelve[p.key] = { name: nm, cn: (MEAN[nm] || {}).cn || "", kind: (MEAN[nm] || {}).kind || "중" };
  });

  /* 십이신살 중 뜻이 또렷한 것만 설명 목록에 올린다 (장성·반안·겁살·재살·망신·월살·육해) */
  const SHOW12 = ["장성살","반안살","지살","겁살","재살","망신살","월살","육해살","천살"];
  SHOW12.forEach(nm => {
    const keys = ps.filter(p => twelveOf(p.branch) === nm).map(p => p.key);
    if (keys.length) add(nm, keys);
  });

  /* ── 설명 붙이기 ── */
  const list = hits.map(h => {
    const m = MEAN[h.name] || { cn:"", kind:"중", s:"", l:"" };
    return {
      name: h.name, cn: m.cn, kind: m.kind,
      where: h.where.map(k => POS_KO[k]).join("·"),
      whereKeys: h.where,
      short: m.s, long: m.l,
      onDay: h.where.indexOf("day") >= 0,
    };
  });
  const order = { 길:0, 중:1, 흉:2 };
  list.sort((a, b) => (order[a.kind] - order[b.kind]) || (b.onDay - a.onDay) || a.name.localeCompare(b.name, "ko"));

  const good = list.filter(x => x.kind === "길");
  const bad  = list.filter(x => x.kind === "흉");
  const mid  = list.filter(x => x.kind === "중");

  /* 기둥별로 모아 표에 뿌릴 것 */
  const byPillar = { year:[], month:[], day:[], hour:[] };
  list.forEach(x => x.whereKeys.forEach(k => byPillar[k].push({ name:x.name, kind:x.kind })));
  POS.forEach(k => { if (gongmang.indexOf((saju.pillars[k] || {}).branch) >= 0) byPillar[k].push({ name:"공망", kind:"흉" }); });

  const parts = [];
  if (good.length) parts.push(`길신 ${good.length}가지`);
  if (mid.length)  parts.push(`쓰기 나름인 자리 ${mid.length}가지`);
  if (bad.length)  parts.push(`조심할 자리 ${bad.length}가지`);
  const summary = parts.length
    ? `${parts.join(", ")}가 걸립니다. 신살은 사주의 뼈대가 아니라 그 위에 덧붙은 표시라, 좋은 것이 많다고 좋은 사주가 되지는 않습니다.`
    : "뚜렷하게 걸리는 신살이 없습니다. 신살로 흔들리지 않는 담백한 구성입니다.";

  return {
    list, good, bad, mid, byPillar, twelve,
    twelveBase: `년지 ${cnJ(yb)}(${yb}) 삼합 ${grp ? grp.split("").map(cnJ).join("") : "-"} 기준`,
    counts: { good: good.length, bad: bad.length, all: list.length },
    summary,
    note: "신살은 사주 여덟 글자를 다 본 뒤에 덧붙여 보는 표시입니다. 같은 신살도 유파마다 뽑는 법이 조금씩 다르고, 신살 하나로 운을 단정하지는 않습니다. 일간의 강약과 용신을 먼저 보시고, 신살은 그 위에 얹는 참고로 보시는 편이 맞습니다.",
  };
}

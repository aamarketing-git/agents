/* 글에서 찾아 주석을 달 용어. 긴 것부터 찾아야 '정관'이 '관'으로 잘리지 않는다 */
export const GLOSS_TERMS = Object.keys(GLOSS).sort((a, b) => b.length - a.length);

/** 한 용어의 쉬운 말 */
export function plainOf(t) { return (GLOSS[t] || {}).plain || ""; }
/** 한 용어의 뜻풀이 */
export function glossOf(t) { return (GLOSS[t] || {}).gloss || ""; }

/** "용어(쉬운 말)" 형태로 */
export function withPlain(t) {
  const p = plainOf(t);
  return p ? `${t}(${p})` : t;
}
